/** Текущий язык определяется из настроек в store.js; t() читает его лениво. */
function t(key) {
  const lang = (window.Store && Store.get('lang')) || 'ru';
  const dict = I18N[lang] || I18N.ru;
  const val = dict[key];
  return val === undefined ? (I18N.ru[key] !== undefined ? I18N.ru[key] : key) : val;
}
